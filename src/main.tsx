/**
 * # 🚀 Application Entry Point
 *
 * Top-level bootstrap file that initialises all application-wide concerns
 * and mounts the React component tree into the DOM.
 *
 * Execution order:
 * - 1. Registers the Vite PWA service worker for offline support and asset caching.
 * - 2. Injects global CSS resets and base styles.
 * - 3. Builds the React Router v7 `BrowserRouter` from the static route config.
 * - 4. Mounts the app inside `<React.StrictMode>` using the React 19 root API.
 *
 * This file intentionally contains no component logic — it is purely a
 * composition root that wires together routing, PWA, styles, and rendering.
 */

// ---------------------------------------------------------------------------- //
//
//  ### ⚛️ React Core
//  Required for JSX transformation and StrictMode wrapper
//
// ---------------------------------------------------------------------------- //

import React from 'react';

// ---------------------------------------------------------------------------- //
//
//  ### 📲 PWA Service Worker
//  Registers the Workbox service worker generated by vite-plugin-pwa
//
// ---------------------------------------------------------------------------- //

/**
 * Virtual module provided by `vite-plugin-pwa` at build time.
 * Exports `registerSW`, a helper that registers the compiled service worker
 * and handles update prompts and auto-reload behaviour.
 */
import { registerSW } from 'virtual:pwa-register';

/**
 * Registers the service worker immediately on module load — before any
 * component rendering — so the SW can begin claiming the page and
 * intercepting fetch requests as early as possible.
 */
registerSW();

// ---------------------------------------------------------------------------- //
//
//  ### 🎨 Global Styles
//  Application-wide CSS applied before any component styles
//
// ---------------------------------------------------------------------------- //

import './styles/global.css';

// ---------------------------------------------------------------------------- //
//
//  ### 🌐 Rendering & Routing
//  React 19 root API and React Router v7 browser router
//
// ---------------------------------------------------------------------------- //

import { createRoot } from 'react-dom/client';
import { createBrowserRouter, RouterProvider } from 'react-router-dom';
import routes from './routes.tsx';

// ---------------------------------------------------------------------------- //
//
//  ### 🏗️ Bootstrap
//  Router instantiation and React tree mount
//
// ---------------------------------------------------------------------------- //

/**
 * Creates the browser router from the imported route config.
 * Instantiated once at module level so the router reference is stable
 * and not re-created on hot module reloads.
 */
const router = createBrowserRouter(routes);

/**
 * Selects the `#root` DOM node defined in `index.html` and mounts the React tree.
 * The non-null assertion (`!`) is safe here — `#root` is always present in `index.html`.
 */
createRoot(document.getElementById('root')!).render(
  <React.StrictMode>
    <RouterProvider router={router} />
  </React.StrictMode>
);
